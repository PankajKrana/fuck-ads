#!/bin/sh
# Removes FuckAds from Linux or macOS and restores the previous DNS settings.
#
#   ./installers/uninstall.sh            keep the configuration file
#   ./installers/uninstall.sh --purge    also delete the configuration
set -eu

PURGE=""
[ "${1:-}" = "--purge" ] && PURGE="--purge"

say()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
if [ "$(id -u)" -eq 0 ]; then SUDO=""; else SUDO="sudo"; fi

# Restores DNS from the backup in the state file when the binary cannot.
# Prints nothing and fails if there is no usable backup or python3.
restore_from_state() {
    [ -f "$1" ] || return 1
    command -v python3 >/dev/null 2>&1 || return 1
    $SUDO python3 -I - "$1" <<'PY'
import json, os, subprocess, sys
dns = json.load(open(sys.argv[1])).get("dns")
if not dns:
    sys.exit(0)
method = dns.get("method")
if method == "mac_os":
    for service, servers in dns["services"]:
        subprocess.run(["networksetup", "-setdnsservers", service] + (servers or ["Empty"]), check=True)
elif method in ("resolv_conf", "network_manager"):
    r = dns["resolv"]
    if r.get("symlink"):
        tmp = "/etc/resolv.conf.fuck-ads-restore"
        if os.path.lexists(tmp):
            os.remove(tmp)
        os.symlink(r["symlink"], tmp)
        os.replace(tmp, "/etc/resolv.conf")
    elif r.get("content") is not None:
        with open("/etc/resolv.conf", "w") as f:
            f.write(r["content"])
elif method != "resolved":
    sys.exit(1)
PY
}

FUCK_ADS="$(command -v fuck-ads 2>/dev/null || true)"
[ -n "$FUCK_ADS" ] || { [ -x /usr/local/bin/fuck-ads ] && FUCK_ADS=/usr/local/bin/fuck-ads; } || true

if [ -n "$FUCK_ADS" ]; then
    say "Running $FUCK_ADS uninstall"
    # Restores DNS from the recorded backup, removes the service, data and binary.
    $SUDO "$FUCK_ADS" uninstall --yes $PURGE && exit 0
    warn "built-in uninstall failed; continuing with manual cleanup"
fi

# Manual cleanup (binary missing or broken).
case "$(uname -s)" in
Linux)
    $SUDO systemctl disable --now fuck-ads.service 2>/dev/null || true
    $SUDO rm -f /etc/systemd/system/fuck-ads.service
    $SUDO systemctl daemon-reload || true
    if [ -f /etc/systemd/resolved.conf.d/90-fuck-ads.conf ]; then
        $SUDO rm -f /etc/systemd/resolved.conf.d/90-fuck-ads.conf
        $SUDO systemctl restart systemd-resolved.service || true
    fi
    if [ -f /etc/NetworkManager/conf.d/90-fuck-ads.conf ]; then
        $SUDO rm -f /etc/NetworkManager/conf.d/90-fuck-ads.conf
        $SUDO systemctl reload NetworkManager.service || true
    fi
    STATE=/var/lib/fuck-ads/system-state.json
    KEEP_STATE=""
    if grep -q "Generated by FuckAds" /etc/resolv.conf 2>/dev/null; then
        if restore_from_state "$STATE"; then
            say "Restored /etc/resolv.conf from the recorded backup"
        elif [ -e /run/systemd/resolve/stub-resolv.conf ]; then
            $SUDO ln -sf /run/systemd/resolve/stub-resolv.conf /etc/resolv.conf
        else
            KEEP_STATE=1
            warn "/etc/resolv.conf still points to FuckAds; restore it manually (e.g. 'nameserver 1.1.1.1'). The backup is kept in $STATE"
        fi
    fi
    if [ -n "$KEEP_STATE" ]; then
        $SUDO rm -rf /var/lib/fuck-ads/data /usr/local/share/fuck-ads
    else
        $SUDO rm -rf /var/lib/fuck-ads /usr/local/share/fuck-ads
    fi
    [ -n "$PURGE" ] && $SUDO rm -rf /etc/fuck-ads
    for d in /etc/opt/chrome/native-messaging-hosts /etc/chromium/native-messaging-hosts \
             /etc/opt/edge/native-messaging-hosts /usr/lib/mozilla/native-messaging-hosts \
             /usr/lib64/mozilla/native-messaging-hosts; do
        $SUDO rm -f "$d/com.fuckads.native.json"
    done
    if id -u fuck-ads >/dev/null 2>&1; then
        $SUDO userdel fuck-ads 2>/dev/null || true
    fi
    ;;
Darwin)
    $SUDO launchctl bootout system/com.fuckads.daemon 2>/dev/null || true
    $SUDO rm -f /Library/LaunchDaemons/com.fuckads.daemon.plist /etc/newsyslog.d/fuck-ads.conf
    STATE="/Library/Application Support/FuckAds/system-state.json"
    KEEP_STATE=""
    if restore_from_state "$STATE"; then
        say "Restored the previous DNS servers from the recorded backup"
    else
        # No usable backup: revert services still on the local resolver to DHCP.
        [ -f "$STATE" ] && KEEP_STATE=1
        networksetup -listallnetworkservices | tail -n +2 | sed 's/^\*//' | while IFS= read -r svc; do
            if networksetup -getdnsservers "$svc" 2>/dev/null | grep -qx "127.0.0.1"; then
                $SUDO networksetup -setdnsservers "$svc" Empty
            fi
        done
    fi
    $SUDO dscacheutil -flushcache; $SUDO killall -HUP mDNSResponder 2>/dev/null || true
    $SUDO rm -rf "/Library/Application Support/FuckAds/data" /Library/Logs/FuckAds /usr/local/share/fuck-ads
    if [ -n "$KEEP_STATE" ]; then
        warn "DNS servers were reset to DHCP; the previous settings are kept in $STATE"
    else
        $SUDO rm -f "$STATE"
        [ -n "$PURGE" ] && $SUDO rm -rf "/Library/Application Support/FuckAds"
    fi
    for d in "/Library/Google/Chrome/NativeMessagingHosts" "/Library/Application Support/Chromium/NativeMessagingHosts" \
             "/Library/Microsoft/Edge/NativeMessagingHosts" "/Library/Application Support/Mozilla/NativeMessagingHosts"; do
        $SUDO rm -f "$d/com.fuckads.native.json"
    done
    $SUDO dscl . -delete /Users/_fuck-ads 2>/dev/null || true
    $SUDO dscl . -delete /Groups/_fuck-ads 2>/dev/null || true
    ;;
esac
$SUDO rm -f /usr/local/bin/fuck-ads /usr/local/bin/fuck-ads-native-host
say "FuckAds removed"
